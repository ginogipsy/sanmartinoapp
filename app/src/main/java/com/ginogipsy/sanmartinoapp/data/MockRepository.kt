    private fun cantina(
        num: Int,
        name: String,
        descIt: String,
        descEn: String,
        year: Int,
        latOff: Double = 0.0,
        lngOff: Double = 0.0,
        foods: List<MenuItem> = emptyList(),
        drinks: List<MenuItem> = emptyList(),
    ): Cantina = Cantina(
        id = "arce-c-%02d".format(num),
        number = num,
        name = name,
        description = LocalizedText(it = descIt, en = descEn),
        firstParticipationYear = year,
        latitude = CENTER_LAT + latOff,
        longitude = CENTER_LNG + lngOff,
        foods = foods,
        drinks = drinks,
    )

    private fun food(idSuffix: String, name: String, descIt: String, descEn: String, plates: Int) =
        MenuItem(
            id = "arce-c-$idSuffix-f",
            name = name,
            description = LocalizedText(it = descIt, en = descEn),
            availablePlates = plates,
            kind = MenuKind.FOOD,
        )

    private fun drink(idSuffix: String, name: String, descIt: String, descEn: String, plates: Int) =
        MenuItem(
            id = "arce-c-$idSuffix-d",
            name = name,
            description = LocalizedText(it = descIt, en = descEn),
            availablePlates = plates,
            kind = MenuKind.DRINK,
        )

    fun getEvents(): List<Event> = events

    fun getEvent(id: String): Event? = events.firstOrNull { it.id == id }

    fun getCantine(): List<Cantina> = cantine.sortedBy { it.number }

    fun getCantina(id: String): Cantina? = cantine.firstOrNull { it.id == id }
